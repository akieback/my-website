#!/usr/bin/env python3
"""Turn a voice recording into the loudness envelope that drives the hero waveform.

Only the envelope (how loud each 20 ms slice is, 0-100) is written to
data/voice.js. The audio itself is never copied into the site, and the words
can't be reconstructed from the envelope.

Usage:
    python3 tools/voice.py ~/Desktop/recording.m4a

Works with anything macOS can decode (m4a, wav, aiff, mp3, caf).
"""

import array
import math
import os
import subprocess
import sys
import struct
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "voice.js"
RATE = 16000
FPS = 50  # envelope samples per second (20 ms each)


def read_wav_data(blob: bytes) -> bytes:
    # afconvert sometimes writes WAVE_FORMAT_EXTENSIBLE headers, which the wave
    # module rejects; the sample data is plain 16-bit PCM either way
    i = 12
    while i + 8 <= len(blob):
        cid, size = blob[i:i + 4], struct.unpack("<I", blob[i + 4:i + 8])[0]
        if cid == b"data":
            data = blob[i + 8:i + 8 + size]
            return data[: len(data) - len(data) % 2]
        i += 8 + size + (size & 1)
    sys.exit("Could not read the converted audio.")


def decode(src: Path) -> array.array:
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "mono.wav"
        subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{RATE}", "-c", "1", str(src), str(wav)], check=True)
        pcm = array.array("h", read_wav_data(wav.read_bytes()))
    if sys.byteorder != "little":
        pcm.byteswap()
    return pcm


def envelope(pcm: array.array) -> list:
    hop = RATE // FPS
    rms = []
    for i in range(0, len(pcm) - hop, hop):
        chunk = pcm[i:i + hop]
        rms.append(math.sqrt(sum(s * s for s in chunk) / hop))
    if not rms:
        sys.exit("Recording is empty.")
    # loudness in dB relative to the loud end of the recording, so quiet and loud
    # recordings both fill the range
    ref = sorted(rms)[int(len(rms) * 0.98)] or 1.0
    db = [20 * math.log10(max(r, 1e-6) / ref) for r in rms]
    # the room's noise floor (quietest 5%) maps to zero, so pauses read as pauses
    noise = sorted(db)[int(len(db) * 0.05)]
    floor = min(-10.0, noise + 1.5)
    env = [min(1.0, max(0.0, (d - floor) / -floor)) for d in db]
    # light smoothing so bars move like speech, not like noise
    sm = [sum(env[max(0, i - 1):i + 2]) / len(env[max(0, i - 1):i + 2]) for i in range(len(env))]
    # trim leading and trailing silence
    lo = next((i for i, v in enumerate(sm) if v > 0.25), 0)
    hi = len(sm) - next((i for i, v in enumerate(reversed(sm)) if v > 0.25), 0)
    sm = sm[max(0, lo - 10):min(len(sm), hi + 10)]
    return [round(v * 100) for v in sm]


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(os.path.expanduser(sys.argv[1]))
    if not src.is_file():
        sys.exit(f"Not found: {src}")
    env = envelope(decode(src))
    seconds = len(env) / FPS
    OUT.write_text(
        "/* Loudness envelope of Adrian's voice (generated by tools/voice.py).\n"
        "   20 ms per value, 0-100. Drives the hero waveform. */\n"
        f"window.VOICE = {{ fps: {FPS}, env: [{','.join(map(str, env))}] }};\n"
    )
    print(f"{seconds:.1f} s of speech -> {len(env)} values -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
